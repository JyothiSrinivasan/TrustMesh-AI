
import re
from io import BytesIO
from xml.sax.saxutils import escape

import markdown

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
    KeepTogether,
)

from backend.database import get_incidents


TEAL = colors.HexColor("#087F76")
DARK = colors.HexColor("#172B40")
LIGHT = colors.HexColor("#E8F5F3")
BORDER = colors.HexColor("#CBD5E1")


def build_incident_pdf(incident_id: int):
    incident = next(
        (i for i in get_incidents() if i["id"] == incident_id),
        None,
    )

    if incident is None:
        return None

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=38,
        bottomMargin=45,
        title=f"TrustMesh AI - Incident {incident_id:04d}",
        author="TrustMesh AI",
    )

    styles = getSampleStyleSheet()

    styles.add(ParagraphStyle(
        name="TMTitle",
        parent=styles["Title"],
        fontSize=21,
        leading=26,
        textColor=TEAL,
        alignment=TA_CENTER,
        spaceAfter=8,
    ))

    styles.add(ParagraphStyle(
        name="TMSubtitle",
        parent=styles["Normal"],
        fontSize=11,
        leading=16,
        textColor=DARK,
        alignment=TA_CENTER,
        spaceAfter=18,
    ))

    styles.add(ParagraphStyle(
        name="TMSection",
        parent=styles["Heading2"],
        fontSize=12,
        leading=16,
        textColor=TEAL,
        spaceBefore=12,
        spaceAfter=6,
        keepWithNext=True,
    ))

    styles.add(ParagraphStyle(
        name="TMAgent",
        parent=styles["Heading3"],
        fontSize=11,
        leading=15,
        textColor=DARK,
        spaceBefore=8,
        spaceAfter=5,
        keepWithNext=True,
    ))

    styles.add(ParagraphStyle(
        name="TMBody",
        parent=styles["BodyText"],
        fontSize=8.5,
        leading=12,
        spaceAfter=5,
        textColor=DARK,
        splitLongWords=True,
    ))

    styles.add(ParagraphStyle(
        name="TMBullet",
        parent=styles["TMBody"],
        leftIndent=14,
        firstLineIndent=-9,
        spaceAfter=5,
    ))

    styles.add(ParagraphStyle(
        name="TMTable",
        parent=styles["TMBody"],
        fontSize=9,
        leading=12,
        spaceAfter=0,
    ))

    story = []

    def plain_paragraph(value, style="TMBody"):
        safe = escape(str(value if value is not None else ""))
        return Paragraph(
            safe.replace("\n", "<br/>"),
            styles[style]
        )

    def add_markdown(text):
        """
        Convert trusted formatting syntax from AI-generated
        Markdown into ReportLab paragraphs.

        Escape source HTML before Markdown conversion so
        model-supplied HTML is not interpreted as markup.
        """
        source = escape(str(text or "No analysis available."))

        html = markdown.markdown(
            source,
            extensions=["sane_lists"],
        )

        # Only preserve a limited subset of formatting.
        html = re.sub(
            r"<h[1-6][^>]*>(.*?)</h[1-6]>",
            r"<strong>\1</strong>",
            html,
            flags=re.I | re.S,
        )

        html = re.sub(r"</?p[^>]*>", "", html, flags=re.I)
        html = re.sub(r"</?ul[^>]*>", "", html, flags=re.I)
        html = re.sub(r"</?ol[^>]*>", "", html, flags=re.I)
        html = re.sub(r"<li[^>]*>", "<br/>&#8226; ", html, flags=re.I)
        html = re.sub(r"</li>", "", html, flags=re.I)
        html = re.sub(r"<br\s*/?>", "<br/>", html, flags=re.I)

        # ReportLab supports <b> and <i>, not arbitrary HTML.
        html = re.sub(r"</?strong>", lambda m: (
            "</b>" if m.group(0).startswith("</") else "<b>"
        ), html, flags=re.I)

        html = re.sub(r"</?em>", lambda m: (
            "</i>" if m.group(0).startswith("</") else "<i>"
        ), html, flags=re.I)

        # Remove any unsupported HTML tags generated by Markdown.
        html = re.sub(
            r"</?(?!b\b|i\b|br\b)[a-z][^>]*>",
            "",
            html,
            flags=re.I,
        )

        # Split paragraphs at blank-line boundaries.
        chunks = re.split(r"\n\s*\n", html)

        for chunk in chunks:
            chunk = chunk.strip()
            if not chunk:
                continue

            chunk = chunk.replace("\n", "<br/>")
            story.append(Paragraph(chunk, styles["TMBody"]))

    def footer(canvas, doc):
        canvas.saveState()
        width, _ = A4

        canvas.setStrokeColor(BORDER)
        canvas.line(45, 36, width - 45, 36)

        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#64748B"))

        canvas.drawString(
            45,
            24,
            "TrustMesh AI | Simulated Security Investigation",
        )

        canvas.drawRightString(
            width - 45,
            24,
            f"Page {doc.page}",
        )

        canvas.restoreState()

    # --------------------------------------------------
    # REPORT HEADER
    # --------------------------------------------------

    story.append(Paragraph("TRUSTMESH AI", styles["TMTitle"]))

    story.append(Paragraph(
        "Zero Trust Security Investigation Report",
        styles["TMSubtitle"],
    ))

    story.append(HRFlowable(
        width="100%",
        thickness=1,
        color=TEAL,
        spaceAfter=15,
    ))

    # --------------------------------------------------
    # INCIDENT DETAILS
    # --------------------------------------------------

    details = [
        ("Incident ID", f"INC-{incident['id']:04d}"),
        ("Timestamp (UTC)", incident["timestamp"]),
        ("User", incident["user_id"]),
        ("Device", incident["device_id"]),
        ("Resource", incident["resource_id"]),
        ("Decision", incident["decision"]),
        ("Risk Score", f"{incident['risk_score']}/100"),
        ("Risk Level", incident["risk_level"]),
    ]

    table = Table(
        [
            [
                plain_paragraph(k, "TMTable"),
                plain_paragraph(v, "TMTable"),
            ]
            for k, v in details
        ],
        colWidths=[130, 365],
        hAlign="LEFT",
    )

    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), LIGHT),
        ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 9),
        ("RIGHTPADDING", (0, 0), (-1, -1), 9),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
    ]))

    story.append(table)

    # --------------------------------------------------
    # RISK INDICATORS
    # --------------------------------------------------

    story.append(Paragraph(
        "Security Risk Indicators",
        styles["TMSection"],
    ))

    reasons = incident.get("reasons") or []

    if reasons:
        for reason in reasons:
            story.append(plain_paragraph(
                "- " + str(reason),
                "TMBullet",
            ))
    else:
        story.append(plain_paragraph(
            "No additional risk indicators were recorded."
        ))

    # --------------------------------------------------
    # AI AGENT INVESTIGATION
    # --------------------------------------------------

    story.append(Paragraph(
        "Five-Agent AI Investigation",
        styles["TMSection"],
    ))

    names = {
        "identity": "Identity Intelligence",
        "device": "Device and Context",
        "behavior": "Behavioral Threat",
        "policy": "Policy Decision",
        "response": "Security Response and Audit",
    }

    agent_results = incident.get("agent_results") or {}

    for key, name in names.items():
        agent = agent_results.get(key, {}) or {}

        analysis = (
            agent.get("analysis")
            or agent.get("message")
            or "No analysis available."
        )

        story.append(KeepTogether([
            Paragraph(name, styles["TMAgent"]),
            plain_paragraph(
                "Agent status: " + str(
                    agent.get("status", "unknown")
                )
            ),
        ]))

        add_markdown(analysis)

        story.append(Spacer(1, 4))

    # --------------------------------------------------
    # REPORT NOTES
    # --------------------------------------------------

    story.append(Paragraph(
        "Report Notes and Limitations",
        styles["TMSection"],
    ))

    story.append(plain_paragraph(
        "This report documents a simulated Zero Trust "
        "security investigation. The deterministic policy "
        "engine determines ALLOW, CHALLENGE, or DENY. "
        "AI-generated explanations are advisory and "
        "require human verification."
    ))

    story.append(plain_paragraph(
        "Identity and device attributes are supplied as "
        "simulation inputs. This prototype does not "
        "implement production identity verification, "
        "device attestation, or live MFA enforcement."
    ))

    document.build(
        story,
        onFirstPage=footer,
        onLaterPages=footer,
    )

    buffer.seek(0)
    return buffer
